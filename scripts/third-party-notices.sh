#!/usr/bin/env bash
# Writes THIRD_PARTY_NOTICES.md: the third-party code that ships with Askbar (what its binaries and images contain), and
# the licenses it is under. Dev-dependencies and build-dependencies are left out, because they are not shipped.
#   Rust: `cargo tree -e normal` for each shipped binary, in the root workspace and in clients/desktop, for every target.
#   npm:  the packages in each lockfile that are not marked `"dev": true`.
# Usage: scripts/third-party-notices.sh          write THIRD_PARTY_NOTICES.md
#        scripts/third-party-notices.sh --check  fail if the file is out of date (needs the crates already fetched, or the network)
# Needs bash, cargo and python3, which the repository already needs.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=THIRD_PARTY_NOTICES.md
CHECK=0; [ "${1:-}" = "--check" ] && CHECK=1
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

tree() { # dir package... -> lines "name vX.Y.Z|license"
  local dir=$1; shift; local p
  for p in "$@"; do
    (cd "$dir" && cargo tree -e normal --target all --prefix none --locked --format '{p}|{l}' -p "$p")
  done
}
{
  tree . askbar-server askbar-admin askbar-auditor askbar-model-gateway askbar-alerter askbar-bootstrap askbar-cpa-supervisor
  tree clients/desktop askbar-client
} > "$TMP/rust.txt"

python3 - "$TMP/rust.txt" "$TMP/new.md" <<'PY'
import json, re, sys
rust_file, out = sys.argv[1], sys.argv[2]
rust = {}
for line in open(rust_file):
    line = line.rstrip("\n")
    if "|" not in line: continue
    head, lic = line.split("|", 1)
    lic = re.sub(r"\s*\(\*\)\s*$", "", lic).strip() or "(none declared)"
    m = re.match(r"(\S+) v(\S+)(?: \((.*?)\))?", head)
    if not m: continue
    name, ver, src = m.groups()
    if src and src.startswith("/"): continue          # Askbar's own crates (a path), not third-party
    rust[(name, ver)] = lic
npm = {}
for lock in ("package-lock.json", "clients/desktop/package-lock.json"):
    for path, p in json.load(open(lock)).get("packages", {}).items():
        if not path or p.get("dev"): continue
        npm[(path.split("node_modules/")[-1], p.get("version", "?"))] = p.get("license", "(none declared)")

o = open(out, "w")
w = lambda s="": o.write(s + "\n")
w("# Third-party notices")
w()
w("Askbar is licensed under the AGPL-3.0-or-later ([LICENSE](LICENSE)). It includes the third-party code below, each under its own license. This file is generated by `scripts/third-party-notices.sh`; do not edit the lists by hand. The images section is written by hand in `scripts/third-party-notices.images.md`.")
w()
w("## Rust crates")
w()
w("What the shipped binaries (the services, the `cpa` supervisor and the desktop app) link, without dev-dependencies and build-dependencies, for every target. The license is the one the crate declares.")
w()
w("| Crate | Version | License |"); w("| --- | --- | --- |")
for (n, v), l in sorted(rust.items()):
    w(f"| {n} | {v} | {l.replace('|', '/')} |")
w()
w("## npm packages")
w()
if npm:
    w("| Package | Version | License |"); w("| --- | --- | --- |")
    for (n, v), l in sorted(npm.items()):
        w(f"| {n} | {v} | {l} |")
else:
    w("None ship. Both lockfiles hold only dev-dependencies (the test browser and the desktop build tool), which are not part of any release. The popup and the admin site use no npm package.")
w()
w(open("scripts/third-party-notices.images.md").read().rstrip("\n"))
PY
if [ "$CHECK" = 1 ]; then
  cmp -s "$TMP/new.md" "$OUT" || { echo "$OUT is out of date: run scripts/third-party-notices.sh" >&2; exit 1; }
  echo "$OUT is up to date"
else
  cp "$TMP/new.md" "$OUT"; echo "wrote $OUT"
fi
