#!/usr/bin/env bash
# Writes compose.release.yaml: compose.yaml with every built service's `build:` block removed and its image set to the
# digest that was published for a release, `ghcr.io/thewuuryar/askbar-<service>@sha256:<digest>`. Everything else stays,
# `container_name` included. Run by .github/workflows/images.yml on a release tag; see docs/guide.md, "Using pre-built images".
#
# Usage: scripts/release-compose.sh <bake-metadata.json> [out]      (out defaults to compose.release.yaml)
#   <bake-metadata.json>  what `docker buildx bake --metadata-file` wrote: one entry for each service, holding
#                         "containerimage.digest". It fails if a built service has no digest.
#   ASKBAR_RELEASE_REGISTRY  the registry, with a trailing slash (default ghcr.io/thewuuryar/).
#
# It relies on the layout of compose.yaml: a service is a two-space-indented key, its `build:` block ends at the next
# four-space-indented key, and its image line is `image: ${ASKBAR_IMAGE_REGISTRY:-}askbar-<service>:${ASKBAR_IMAGE_TAG:-latest}`.
# It stops if a built service does not have that image line, so a change of layout is noticed here and not in a release.
#
# The result is NOT self-contained. It still uses files of the repository: the data directory (`${DATA_DIR:-./data}`),
# the dev profile's `./tests/e2e/mock_llm.py`, and `.env` (from `.env.example`). Deploy a release from a checkout of its tag
# (`git clone --branch v1.0.0 ...`) with `compose.release.yaml` in place of `compose.yaml`. The script lists every
# repository-relative bind mount it kept, so a new one is noticed.
set -euo pipefail
cd "$(dirname "$0")/.."
META=${1:?usage: scripts/release-compose.sh <bake-metadata.json> [out]}
OUT=${2:-compose.release.yaml}
REGISTRY=${ASKBAR_RELEASE_REGISTRY:-ghcr.io/thewuuryar/}
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

# "service digest" for every entry of the metadata file.
python3 - "$META" > "$TMP/digests" <<'PY'
import json, re, sys
for name, entry in json.load(open(sys.argv[1])).items():
    d = entry.get("containerimage.digest", "") if isinstance(entry, dict) else ""
    if re.fullmatch(r"sha256:[0-9a-f]{64}", d):
        print(name, d)
PY

awk -v registry="$REGISTRY" -v digests="$TMP/digests" '
  BEGIN {
    while ((getline line < digests) > 0) { split(line, p, " "); digest[p[1]] = p[2] }
    print "# Generated by scripts/release-compose.sh from compose.yaml: every built service uses the image published for"
    print "# this release, by digest. It still needs this checkout (the data directory, the dev profile and .env)."
  }
  /^[A-Za-z]/ { in_services = ($0 == "services:"); skipping = 0 }
  in_services && /^  [A-Za-z0-9_-]+:[ ]*$/ { svc = $0; gsub(/[ :]/, "", svc); skipping = 0 }
  in_services && /^    build:/ { skipping = 1; built[svc] = 1; next }
  skipping && /^     / { next }            # a line of the build block (six spaces)
  skipping && /^[ ]*$/ { next }
  { skipping = 0 }
  in_services && /^    image: \$\{ASKBAR_IMAGE_REGISTRY:-\}askbar-/ {
    if (!(svc in built)) { printf "error: %s has the registry image line but no build block\n", svc > "/dev/stderr"; bad = 1; next }
    if (!(svc in digest)) { printf "error: no digest for %s in the metadata\n", svc > "/dev/stderr"; bad = 1; next }
    printf "    image: %saskbar-%s@%s\n", registry, svc, digest[svc]
    done[svc] = 1
    next
  }
  { print }
  END {
    for (s in built) if (!(s in done)) { printf "error: %s is built but its image line was not found\n", s > "/dev/stderr"; bad = 1 }
    exit bad
  }
' compose.yaml > "$TMP/out.yaml" || { echo "release-compose.sh: failed, nothing written" >&2; exit 1; }

if grep -q '^    build:' "$TMP/out.yaml"; then echo "release-compose.sh: a build block is left" >&2; exit 1; fi
mv "$TMP/out.yaml" "$OUT"
echo "wrote $OUT ($(grep -c "image: ${REGISTRY}askbar-.*@sha256:" "$OUT") Askbar images by digest)"
echo "repository-relative bind mounts it keeps (a release is deployed from a checkout of its tag):"
grep -E '^\s+- (\./|\$\{[A-Z_]+:-\./)' "$OUT" | sed 's/^ */  /' | sort -u
